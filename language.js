function changeLanguage(lang) {
  localStorage.setItem('preferred-lang', lang);
  
  if (lang === 'ar') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.documentElement.setAttribute('lang', 'ar');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.setAttribute('lang', 'en');
  }

  const map = lang === 'ar' ? dictionary : Object.fromEntries(Object.entries(dictionary).map(([k, v]) => [v, k]));
  
  // معالجة خاصة لترجمة كلمة Welcome مع اسم المستخدم
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while (node = walk.nextNode()) {
    let originalText = node.nodeValue.trim();
    if (originalText.length > 0) {
      if (lang === 'ar' && originalText.includes('Welcome')) {
        node.nodeValue = originalText.replace(/Welcome/gi, 'مرحباً');
      } else if (lang === 'en' && originalText.includes('مرحباً')) {
        node.nodeValue = originalText.replace(/مرحباً/g, 'Welcome');
      }

      let cleanText = originalText.replace(/^[.!?,]+|[.!?,]+$/g, "").trim();
      
      if (map[originalText]) {
        node.nodeValue = node.nodeValue.replace(originalText, map[originalText]);
      } else if (map[cleanText]) {
        node.nodeValue = node.nodeValue.replace(cleanText, map[cleanText]);
      } else {
        for (let key in map) {
          if (originalText.includes(key)) {
            node.nodeValue = node.nodeValue.replace(key, map[key]);
          }
        }
      }
    }
  }

  document.querySelectorAll('input, textarea').forEach(element => {
    if (element.placeholder) {
      let pText = element.placeholder.trim();
      if (map[pText]) {
        element.placeholder = map[pText];
      }
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('preferred-lang') || 'ar';
  if (savedLang === 'ar') {
    changeLanguage('ar');
  }
});